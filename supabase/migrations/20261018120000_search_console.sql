-- Google Search Console tracking and IndexNow log (src/lib/seo/gsc.ts, src/lib/seo/indexnow.ts,
-- scripts/seo/gsc-sync.ts, /api/cron/gsc-sync). Additive and idempotent. Touches no existing rows.
--
-- 1. gsc_search_analytics   one row per (date, query, page, country, device) from searchanalytics.query.
--                           Dimensions a fetch did not ask for are stored as '' (not NULL) so the unique key holds.
--                           grain says which fetch wrote the row:
--                             'site'  dimensions [date]               site totals (include anonymised queries)
--                             'page'  dimensions [date, page]         per-page totals (include anonymised queries)
--                             'query' dimensions [date, query, page]  (+ country/device when configured)
--                           query_key is the Keyword Planner match key (kpKey in scripts/brain/lib/topical-map/
--                           keyword-planner.ts) so queries join to the topical map without re-normalising in SQL.
-- 2. gsc_url_inspection     one row per urlInspection.index.inspect call (history kept; latest per URL in a view).
-- 3. indexnow_submissions   one row per URL per IndexNow POST.
-- 4. gsc_query_topics / gsc_page_topics   query_key -> topic and page URL -> topic, rewritten by each sync from
--                           the topical map (kg_nodes type 'topic'). gsc_topic_daily aggregates through them.
-- 5. Read functions for the admin page (period totals by query, page and day).
--
-- Service role only, like the knowledge graph: RLS on, no anon/authenticated policies, privileges revoked,
-- views run as the caller (security_invoker) and are revoked too.

-- ---------------------------------------------------------------------
-- 1. Search analytics
-- ---------------------------------------------------------------------
create table if not exists public.gsc_search_analytics (
  id bigint generated by default as identity primary key,
  date date not null,
  grain text not null default 'query' check (grain in ('site', 'page', 'query')),
  query text not null default '',
  query_key text not null default '',
  page text not null default '',
  country text not null default '',
  device text not null default '',
  clicks integer not null default 0,
  impressions integer not null default 0,
  ctr double precision not null default 0,
  position double precision not null default 0,
  fetched_at timestamptz not null default now(),
  constraint gsc_search_analytics_row_key unique (date, query, page, country, device)
);

create index if not exists gsc_search_analytics_date_idx on public.gsc_search_analytics (date);
create index if not exists gsc_search_analytics_grain_date_idx on public.gsc_search_analytics (grain, date);
create index if not exists gsc_search_analytics_query_key_idx on public.gsc_search_analytics (query_key) where grain = 'query';
create index if not exists gsc_search_analytics_page_idx on public.gsc_search_analytics (page, date) where page <> '';

-- ---------------------------------------------------------------------
-- 2. URL inspection
-- ---------------------------------------------------------------------
create table if not exists public.gsc_url_inspection (
  id bigint generated by default as identity primary key,
  url text not null,
  inspected_at timestamptz not null default now(),
  verdict text,
  coverage_state text,
  indexing_state text,
  page_fetch_state text,
  robots_txt_state text,
  last_crawl_time timestamptz,
  google_canonical text,
  user_canonical text,
  raw jsonb not null default '{}'::jsonb
);

create index if not exists gsc_url_inspection_url_idx on public.gsc_url_inspection (url, inspected_at desc);
create index if not exists gsc_url_inspection_inspected_idx on public.gsc_url_inspection (inspected_at desc);

create or replace view public.gsc_url_inspection_latest
with (security_invoker = true) as
select distinct on (url)
  id, url, inspected_at, verdict, coverage_state, indexing_state, page_fetch_state, robots_txt_state,
  last_crawl_time, google_canonical, user_canonical
from public.gsc_url_inspection
order by url, inspected_at desc;

-- ---------------------------------------------------------------------
-- 3. IndexNow log
-- ---------------------------------------------------------------------
create table if not exists public.indexnow_submissions (
  id bigint generated by default as identity primary key,
  url text not null,
  submitted_at timestamptz not null default now(),
  engine text not null default 'indexnow',
  endpoint text not null,
  status_code integer,
  response text,
  trigger text
);

create index if not exists indexnow_submissions_url_idx on public.indexnow_submissions (url, submitted_at desc);
create index if not exists indexnow_submissions_submitted_idx on public.indexnow_submissions (submitted_at desc);

-- ---------------------------------------------------------------------
-- 4. Topic mapping
-- ---------------------------------------------------------------------
create table if not exists public.gsc_query_topics (
  query_key text primary key,
  topic_id text not null,
  match text not null check (match in ('head_term', 'search_term', 'query')),
  updated_at timestamptz not null default now()
);

create table if not exists public.gsc_page_topics (
  page text primary key,
  topic_id text not null,
  match text not null check (match in ('asset', 'content_post')),
  updated_at timestamptz not null default now()
);

create index if not exists gsc_query_topics_topic_idx on public.gsc_query_topics (topic_id);
create index if not exists gsc_page_topics_topic_idx on public.gsc_page_topics (topic_id);

-- Query rows by topic and day. A query that matches a topic's phrasing wins; otherwise the page's topic.
-- avg_position: impression-weighted mean of Google's average position (1 = top).
create or replace view public.gsc_topic_daily
with (security_invoker = true) as
select
  coalesce(qt.topic_id, pt.topic_id) as topic_id,
  a.date,
  sum(a.clicks)::bigint as clicks,
  sum(a.impressions)::bigint as impressions,
  case when sum(a.impressions) > 0 then sum(a.position * a.impressions) / sum(a.impressions) end as avg_position
from public.gsc_search_analytics a
left join public.gsc_query_topics qt on qt.query_key = a.query_key
left join public.gsc_page_topics pt on pt.page = a.page
where a.grain = 'query'
  and coalesce(qt.topic_id, pt.topic_id) is not null
group by 1, 2;

-- ---------------------------------------------------------------------
-- 5. Read functions (admin page). Period totals, impression-weighted positions.
-- ---------------------------------------------------------------------
create or replace function public.gsc_query_totals(p_start date, p_end date, p_limit integer default 2000)
returns table (query text, query_key text, clicks bigint, impressions bigint, ctr double precision, avg_position double precision, top_page text)
language sql
stable
set search_path = public
as $$
  with q as (
    select a.query, a.query_key, a.page, sum(a.clicks) as clicks, sum(a.impressions) as impressions,
           sum(a.position * a.impressions) as pos_w
    from public.gsc_search_analytics a
    where a.grain = 'query' and a.date between p_start and p_end
    group by a.query, a.query_key, a.page
  ), ranked as (
    select q.*, row_number() over (partition by q.query order by q.clicks desc, q.impressions desc) as rn from q
  )
  select r.query,
         min(r.query_key),
         sum(r.clicks)::bigint,
         sum(r.impressions)::bigint,
         case when sum(r.impressions) > 0 then sum(r.clicks)::double precision / sum(r.impressions) else 0 end,
         case when sum(r.impressions) > 0 then sum(r.pos_w) / sum(r.impressions) end,
         max(case when r.rn = 1 then r.page end)
  from ranked r
  group by r.query
  order by sum(r.impressions) desc, r.query
  limit greatest(1, least(p_limit, 25000));
$$;

create or replace function public.gsc_page_totals(p_start date, p_end date)
returns table (page text, clicks bigint, impressions bigint, ctr double precision, avg_position double precision)
language sql
stable
set search_path = public
as $$
  select a.page,
         sum(a.clicks)::bigint,
         sum(a.impressions)::bigint,
         case when sum(a.impressions) > 0 then sum(a.clicks)::double precision / sum(a.impressions) else 0 end,
         case when sum(a.impressions) > 0 then sum(a.position * a.impressions) / sum(a.impressions) end
  from public.gsc_search_analytics a
  where a.grain = 'page' and a.date between p_start and p_end
  group by a.page
  order by sum(a.impressions) desc, a.page;
$$;

create or replace function public.gsc_topic_totals(p_start date, p_end date)
returns table (topic_id text, clicks bigint, impressions bigint, avg_position double precision)
language sql
stable
set search_path = public
as $$
  select d.topic_id,
         sum(d.clicks)::bigint,
         sum(d.impressions)::bigint,
         case when sum(d.impressions) > 0 then sum(d.avg_position * d.impressions) / sum(d.impressions) end
  from public.gsc_topic_daily d
  where d.date between p_start and p_end
  group by d.topic_id;
$$;

