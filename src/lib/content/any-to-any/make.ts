/** Replace em dashes (and spaced en dashes) with commas. Numeric ranges like 6–10 are kept. */
export function stripEmDashes(text: string): string {
  return text
    .replace(/\s*—\s*/g, ', ')
    .replace(/\s+–\s+/g, ', ')
    .replace(/,\s*,/g, ',')
    .replace(/^,\s*/gm, '')
    .replace(/,\s*([.!?])/g, '$1');
}

function wordCount(s: string): number {
  return s.trim() ? s.trim().split(/\s+/).length : 0;
}

/** Format, voice and claim checks. Every hit becomes a warning; nothing blocks the draft. */
export function lintMade(body: string, target: PieceType, pack: Pick<VoicePack, 'bannedTerms' | 'aiProsePatterns'>): string[] {
  const spec = TARGET_SPECS[target];
  const warnings: string[] = [];
  if (!body.trim()) warnings.push('The model returned an empty body.');
  if (spec?.words && !spec.video && !spec.frames) {
    const n = wordCount(body);
    if (n < spec.words[0] || n > spec.words[1]) {
      warnings.push(`${n} words; ${spec.label} wants ${spec.words[0]} to ${spec.words[1]}.`);
    }
  }
  if (spec?.maxChars && body.trim().length > spec.maxChars) {
    warnings.push(`${body.trim().length} characters; ${spec.label} allows ${spec.maxChars}.`);
  }
  if (spec?.frames) {
    const frames = body.split(/\n\s*---\s*\n/).filter((f) => f.trim());
    if (frames.length < spec.frames[0] || frames.length > spec.frames[1]) {
      warnings.push(`${frames.length} frames; carousels use ${spec.frames[0]} to ${spec.frames[1]}.`);
    }
    const long = frames.findIndex((f) => wordCount(f) > 25);
    if (long >= 0) warnings.push(`Frame ${long + 1} is over 25 words.`);
  }
  if (spec?.noLinks && /https?:\/\/|www\.|\b[a-z0-9-]+\.(?:com|online|org|net)\//i.test(body)) {
    warnings.push(`${spec.label} should carry no links; remove the link.`);
  }
  if (spec?.maxHashtags !== undefined) {
    const tags = body.match(/(?:^|\s)#[\p{L}\p{N}_]+/gu)?.length ?? 0;
    if (tags > spec.maxHashtags) warnings.push(`${tags} hashtags; ${spec.label} allows ${spec.maxHashtags}.`);
  }
  if (/linkedin/i.test(body)) warnings.push('Mentions LinkedIn (no LinkedIn).');
  if (/\bcrypto|bitcoin|\bnft\b/i.test(body)) warnings.push('Mentions crypto (never crypto).');
  const needs = body.match(/\[NEEDS SOURCE\]/g)?.length ?? 0;
  if (needs) warnings.push(`${needs} claim${needs > 1 ? 's' : ''} marked [NEEDS SOURCE]: source or cut before publishing.`);
  const gaps = body.match(/\[AUSTIN:[^\]]*\]/g)?.length ?? 0;
  if (gaps) warnings.push(`${gaps} [AUSTIN] gap${gaps > 1 ? 's' : ''} to fill in his words.`);
  for (const m of findBannedTerms(body, pack)) warnings.push(`Banned term "${m.match}": ${m.excerpt}`);
  for (const m of findAiProse(body, pack)) warnings.push(`AI prose "${m.match}": ${m.excerpt}`);
  return warnings;
}

