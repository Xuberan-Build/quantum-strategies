function researchRulesBlock(direction: Direction): string {
  return [direction === 'up' ? UP_RESEARCH_RULE : SAME_RESEARCH_RULE, 'RESEARCH RULES:', ...RESEARCH_RULES.map((r) => `- ${r}`)].join('\n');
}

export function directionRule(direction: Direction): string {
  return direction === 'up' ? UP_RULE : direction === 'down' ? DOWN_RULE : SAME_RULE;
}

