/** The user prompt for a text target (video targets build their brief from the same parts). */
export function buildMakePrompt({ source, sourceRef, target, direction, insight, extraContext, research }: MakePromptInput): {
  role: string;
  user: string;
  maxTokens: number;
} {
  const spec = TARGET_SPECS[target];
  if (!spec) throw new MakeError(`Target not offered: ${target}`);
  const metaKeys = spec.meta ?? {};
  const output = [
    'OUTPUT: one JSON object, nothing else, with keys:',
    '- "title": a short working title for the calendar (for a Reddit post, the post title)',
    `- "body": the ${spec.label} itself, ready to paste`,
    `- "meta": { ${Object.entries(metaKeys).map(([k, d]) => `"${k}": ${d}`).join('; ') || 'empty object'} }`,
  ].join('\n');
  const user = [
    `Make a new ${spec.label} (${target}) from this ${sourceRef.kind === 'piece' ? `${targetLabel(source.form)} piece` : source.form === 'article' ? 'pillar article' : `${sourceRef.kind} (${targetLabel(source.form)})`}.`,
    '',
    directionRule(direction),
    research ? `\n${researchRulesBlock(direction)}` : '',
    '',
    `FORMAT: ${spec.label}`,
    ...spec.rules.map((r) => `- ${r}`),
    ...SHARED_RULES.map((r) => `- ${r}`),
    source.articleUrl ? `\nARTICLE URL (the cornerstone, use only where the format allows a link): ${source.articleUrl}` : '',
    insight && sourceRef.kind !== 'insight' ? `\nTHE INSIGHT THIS CARRIES:\n${insightBlock(insight)}` : '',
    research ? `\n${researchBlock(research)}` : '',
    `\nSOURCE${source.title ? `: ${source.title}` : ''}\n"""\n${source.text.slice(0, MAX_SOURCE_CHARS)}\n"""`,
    extraContext?.trim() && sourceRef.kind !== 'external' ? `\nEXTRA CONTEXT FROM AUSTIN:\n${extraContext.trim()}` : '',
    '',
    output,
  ]
    .filter((l) => l !== '')
    .join('\n');
  return { role: spec.role, user, maxTokens: spec.maxTokens };
}

