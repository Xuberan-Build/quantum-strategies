/** What the UI shows under "Research used". */
export interface ResearchSummary {
  topic: { id: string; title: string; matchedBy: string; reason: string } | null;
  sources: number;
  firstHand: number;
  questions: number;
  links: number;
  gaps: string[];
  /** Long targets get the "Run the full research pipeline" handoff. */
  long: boolean;
}

export interface MakeResult {
  piece: { id: string; title: string | null; piece_type: PieceType };
  linkId: string | null;
  warnings: string[];
  /** Null when no research pack was built (short targets going down or across). */
  research: ResearchSummary | null;
}

export function researchSummary(pack: ResearchPack, target: PieceType): ResearchSummary {
  const t = pack.topics[0];
  return {
    topic: t ? { id: t.id, title: t.title, matchedBy: t.matchedBy, reason: t.matchReason } : null,
    sources: pack.counts.sources,
    firstHand: pack.counts.firstHand,
    questions: pack.counts.questions,
    links: pack.counts.links,
    gaps: pack.gaps,
    long: RESEARCH_LONG_TARGETS.includes(target),
  };
}

/** Count the open markers in a draft (video scripts skip lintMade, so they are counted here too). */
export function markerWarnings(body: string): string[] {
  const out: string[] = [];
  const needs = body.match(/\[NEEDS SOURCE\]/g)?.length ?? 0;
  if (needs) out.push(`${needs} claim${needs > 1 ? 's' : ''} marked [NEEDS SOURCE]: source or cut before publishing.`);
  const gaps = body.match(/\[AUSTIN:[^\]]*\]/g)?.length ?? 0;
  if (gaps) out.push(`${gaps} [AUSTIN] gap${gaps > 1 ? 's' : ''} to fill in his words.`);
  return out;
}

interface Generated {
  title: string | null;
  body: string;
  meta: Record<string, unknown>;
  warnings: string[];
}

async function generateTextTarget(
  pack: VoicePack,
  input: MakePromptInput,
): Promise<Generated> {
  const { role, user, maxTokens } = buildMakePrompt(input);
  const system = buildVoiceSystemPrompt(pack, { role, includeCanon: input.direction === 'up' });
  const res = await generateText({
    tier: 'standard',
    system,
    messages: [{ role: 'user', content: user }],
    json: true,
    maxTokens,
  });
  const warnings: string[] = [];
  if (res.finishReason === 'length') warnings.push('The model ran out of room; the draft may be cut off.');
  try {
    const parsed = parseJsonReply<{ title?: unknown; body?: unknown; meta?: unknown }>(res.text);
    const meta = parsed.meta && typeof parsed.meta === 'object' ? (parsed.meta as Record<string, unknown>) : {};
    return {
      title: typeof parsed.title === 'string' ? parsed.title : null,
      body: typeof parsed.body === 'string' ? parsed.body : String(parsed.body ?? ''),
      meta,
      warnings,
    };
  } catch {
    warnings.push('The model did not return JSON; the raw reply was saved as the body.');
    return { title: null, body: res.text ?? '', meta: {}, warnings };
  }
}

async function generateVideoTarget(
  pack: VoicePack,
  input: MakePromptInput,
  variant: 'long' | 'short',
): Promise<Generated> {
  const { source, direction, insight, extraContext, sourceRef, research } = input;
  const rules: VideoScriptRules = {
    bannedTerms: pack.bannedTerms,
    handleWithCare: pack.handleWithCare,
    ctaSpamPatterns: pack.ctaSpamPatterns,
    outcomeTimeboxPatterns: pack.outcomeTimeboxPatterns,
    aiProsePatterns: pack.aiProsePatterns,
  };
  const voiceGuide = buildVoiceSystemPrompt(pack, {
    role: `${TARGET_SPECS[variant === 'long' ? 'youtube_long' : 'short']!.role} Spoken word for camera, plus on-screen text and b-roll cues.`,
    includeCanon: true,
  });
  const material = [
    directionRule(direction),
    research ? researchRulesBlock(direction) : '',
    variant === 'short' ? 'The spoken CTA is "It\'s on my profile". Never "link below".' : '',
    insight && sourceRef.kind !== 'insight' ? `THE INSIGHT THIS CARRIES:\n${insightBlock(insight)}` : '',
    extraContext?.trim() && sourceRef.kind !== 'external' ? `EXTRA CONTEXT FROM AUSTIN:\n${extraContext.trim()}` : '',
    research ? researchBlock(research, { omitSources: true }) : '',
    `SOURCE (${targetLabel(source.form)}):\n${source.text}`,
  ]
    .filter(Boolean)
    .join('\n\n');
  const maxTokens = TARGET_SPECS[variant === 'long' ? 'youtube_long' : 'short']!.maxTokens;
  const result = await generateValidatedVideoScript({
    variant,
    rules,
    voiceGuide,
    complete: async (system, user) => {
      const res = await generateText({ tier: 'standard', system, messages: [{ role: 'user', content: user }], json: true, maxTokens });
      return res.text ?? '';
    },
    brief: {
      title: source.title ?? 'Untitled',
      ctaTarget: 'the free quiz',
      material: material.slice(0, 16000),
      ...(research ? { sources: sourcesBlock(research) } : {}),
    },
  });
  const { validation } = result;
  if (!validation.script) {
    throw new MakeError(
      `The model's output did not parse as a video script: ${validation.errors.slice(0, 3).map((e) => e.message).join('; ')}`,
      502,
    );
  }
  const { script, ...validationRest } = validation;
  const warnings = validation.pass
    ? []
    : [`Script failed validation after ${result.attempts} attempt(s): ${validation.errors.slice(0, 5).map((e) => e.code).join(', ')}. Saved as a draft to fix by hand.`];
  return {
    title: script.title,
    body: renderVideoScript(script, validation),
    meta: {
      format: 'video_script',
      variant,
      schema_version: VIDEO_SCRIPT_SCHEMA_VERSION,
      script,
      validation: validationRest,
      attempts: result.attempts,
      attempt_history: result.history,
    },
    warnings,
  };
}

function cleanMeta(meta: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(meta)) out[k] = typeof v === 'string' ? stripEmDashes(v) : v;
  return out;
}

/** A missing-column error from PostgREST (migration not applied yet). */
function isMissingColumn(err: { code?: string; message?: string } | null, column: string): boolean {
  return !!err && (err.code === 'PGRST204' || err.code === '42703') && (err.message ?? '').includes(column);
}

export async function makeAsset(
  client: SupabaseClient,
  args: {
    source: AssetRef;
    target: PieceType;
    insightId?: string | null;
    createdBy?: string | null;
    extraContext?: string;
    scheduledFor?: string | null;
  },
): Promise<MakeResult> {
  const { target } = args;
  if (!isOfferedTarget(target)) throw new MakeError(`Target not offered: ${String(target)}`);
  if (args.insightId && !UUID_RE.test(args.insightId)) throw new MakeError('insightId must be a uuid');

  const source = await loadSource(client, args.source, args.extraContext);
  const spec = TARGET_SPECS[target]!;
  const samePlatform = !!source.platform && source.platform === spec.platform;
  const direction = directionFor(source.form, target, samePlatform);
  const insightId = args.insightId ?? source.insightId ?? null;

  let insight: InsightRow | null = null;
  if (insightId && args.source.kind !== 'insight') {
    const { data } = await client
      .from('content_insights')
      .select('line, claim, source_kind, source_ref, evidence_tier, notes')
      .eq('id', insightId)
      .maybeSingle();
    insight = (data as InsightRow | null) ?? null;
  }

  // Research pack: always going up; for long targets going across or down too.
  let research: ResearchPack | null = null;
  const researchWarnings: string[] = [];
  if (wantsResearch(direction, target)) {
    try {
      research = await buildResearchPack(client, {
        source: { ...source, insightId },
        target,
        extraContext: args.extraContext ?? null,
        extraIsSource: args.source.kind === 'external',
      });
      for (const g of research.gaps) researchWarnings.push(`Research gap: ${g}`);
    } catch (e) {
      researchWarnings.push(`The research pack could not be built (${e instanceof Error ? e.message : String(e)}); the draft was made from the source alone.`);
    }
  }

  const voice = await getVoicePackResult();
  const input: MakePromptInput = { source, sourceRef: args.source, target, direction, insight, extraContext: args.extraContext, research };
  const gen = spec.video ? await generateVideoTarget(voice.pack, input, spec.video) : await generateTextTarget(voice.pack, input);

  const body = stripEmDashes(gen.body).trim();
  const title = gen.title ? stripEmDashes(gen.title).trim() : source.title ? `${spec.label}: ${source.title}`.slice(0, 200) : spec.label;
  const meta = cleanMeta(gen.meta);
  const warnings = [...gen.warnings, ...(spec.video ? markerWarnings(body) : lintMade(body, target, voice.pack)), ...researchWarnings];
  if (target === 'reddit' || target === 'reddit_post') {
    warnings.push('Reddit: Austin rewrites this in his own words and posts by hand (several subs ban AI-written posts).');
  }

  const row: Record<string, unknown> = {
    angle_id: source.angleId ?? null,
    piece_type: target,
    title,
    body,
    status: 'draft',
    source_post_id: source.sourcePostId ?? null,
    insight_id: insightId,
    scheduled_for: args.scheduledFor ?? null,
    notes: `Made from ${args.source.kind} ${args.source.id}`,
    platform_meta: {
      ...meta,
      made_from: { kind: args.source.kind, id: args.source.id },
      direction,
      source_form: source.form,
      made_by: args.createdBy ?? null,
      made_at: new Date().toISOString(),
      voice_pack: { source: voice.source, version: voice.pack.version },
      model: activeModelLabel('standard'),
      warnings,
      ...(research ? { research: researchMeta(research) } : {}),
    },
  };

  let { data: piece, error } = await client.from('content_pieces').insert(row).select('id, title, piece_type').single();
  if (error && isMissingColumn(error, 'insight_id')) {
    // Migration 20261101180000 not applied yet: save without the insight column.
    delete row.insight_id;
    warnings.push('content_pieces.insight_id is missing (apply the any-to-any migration); the insight was not attached.');
    ({ data: piece, error } = await client.from('content_pieces').insert(row).select('id, title, piece_type').single());
  }
  if (error || !piece) {
    const msg =
      error?.code === '23514'
        ? `content_pieces.piece_type does not allow '${target}' yet; apply the any-to-any migration.`
        : `Could not save the piece: ${error?.message ?? 'unknown error'}`;
    throw new MakeError(msg, 500);
  }

  let linkId: string | null = null;
  const { data: link, error: linkErr } = await client
    .from('content_asset_links')
    .insert({
      from_kind: args.source.kind,
      from_id: args.source.id,
      to_kind: 'piece',
      to_id: piece.id,
      direction,
      insight_id: insightId,
      note: `Made ${spec.label} from ${args.source.kind}`,
      created_by: args.createdBy ?? null,
    })
    .select('id')
    .single();
  if (linkErr || !link) warnings.push(`The piece was saved but the asset link was not: ${linkErr?.message ?? 'unknown error'}`);
  else linkId = link.id;

  return {
    piece: { id: piece.id, title: piece.title ?? null, piece_type: piece.piece_type as PieceType },
    linkId,
    warnings,
    research: research ? researchSummary(research, target) : null,
  };
}
