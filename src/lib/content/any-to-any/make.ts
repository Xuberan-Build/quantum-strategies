export const OFFERED_TARGETS = Object.keys(TARGET_SPECS) as PieceType[];

export function isOfferedTarget(t: unknown): t is PieceType {
  return typeof t === 'string' && t in TARGET_SPECS && t !== 'social_linkedin' && t !== 'gpt_product';
}

export function isSourceForm(f: unknown): f is SourceForm {
  return typeof f === 'string' && f in FORM_RANK;
}

/** Offered forms grouped by length relative to the source (FORM_RANK), longest first. */
export function offeredTargets(sourceForm: SourceForm): { longer: PieceType[]; same: PieceType[]; shorter: PieceType[] } {
  const rank = FORM_RANK[sourceForm] ?? FORM_RANK.blog;
  const sorted = [...OFFERED_TARGETS].sort((a, b) => FORM_RANK[b] - FORM_RANK[a]);
  return {
    longer: sorted.filter((t) => FORM_RANK[t] > rank),
    same: sorted.filter((t) => FORM_RANK[t] === rank),
    shorter: sorted.filter((t) => FORM_RANK[t] < rank),
  };
}

export function targetLabel(t: string): string {
  return TARGET_SPECS[t as PieceType]?.label ?? t;
}

/** Platform family of a form (used when the source row doesn't say). */
export function platformOfForm(form: SourceForm): string {
  if (form === 'article') return 'site';
  if (form === 'email_sequence') return 'email';
  return TARGET_SPECS[form]?.platform ?? 'site';
}

// ── Loading sources ─────────────────────────────────────────────────────────

/** Map a stored piece_type (incl. legacy ones) to a form on the length scale. */
function pieceForm(pieceType: string, meta: Record<string, unknown> | null): SourceForm {
  if (pieceType in FORM_RANK) return pieceType as SourceForm;
  if (pieceType === 'video_script') return meta?.variant === 'short' ? 'short' : 'youtube_long';
  if (pieceType === 'social_linkedin') return 'social_ig';
  return 'blog';
}

/** Social publisher target format → form. */
function socialForm(format: string | undefined, platform: string | undefined): SourceForm {
  switch (format) {
    case 'video':
      return 'youtube_long';
    case 'short':
    case 'reel':
    case 'trial_reel':
    case 'tiktok_video':
      return 'short';
    case 'carousel':
    case 'tiktok_photo':
      return 'ig_carousel';
    case 'tweet':
    case 'thread':
      return 'social_twitter';
    default:
      return platform === 'x' || platform === 'threads' ? 'social_twitter' : 'social_ig';
  }
}

/** Best guess at an external url's form and platform. */
export function externalForm(url: string): { form: SourceForm; platform: string } {
  const u = url.toLowerCase();
  if (u.includes('reddit.com')) {
    // /r/sub/comments/<post>/<slug>/<comment>/ is a comment permalink
    const parts = u.split('/comments/')[1]?.split('/').filter(Boolean) ?? [];
    return { form: parts.length >= 3 ? 'reddit' : 'reddit_post', platform: 'reddit' };
  }
  if (/(^|\/\/|\.)(x|twitter)\.com/.test(u)) return { form: u.includes('/i/article') || u.includes('/article/') ? 'x_article' : 'social_twitter', platform: 'x' };
  if (u.includes('youtube.com/shorts') ) return { form: 'short', platform: 'youtube' };
  if (u.includes('youtube.com') || u.includes('youtu.be')) return { form: 'youtube_long', platform: 'youtube' };
  if (u.includes('instagram.com')) return { form: u.includes('/reel') ? 'short' : 'social_ig', platform: 'instagram' };
  if (u.includes('tiktok.com')) return { form: 'short', platform: 'tiktok' };
  if (u.includes('quantumstrategies.online/articles')) return { form: 'article', platform: 'site' };
  return { form: 'blog', platform: 'site' };
}

function one<T>(v: T | T[] | null | undefined): T | null {
  return Array.isArray(v) ? (v[0] ?? null) : (v ?? null);
}

export async function loadSource(client: SupabaseClient, ref: AssetRef, extraContext?: string): Promise<LoadedSource> {
  if (!ASSET_KINDS.includes(ref.kind)) throw new MakeError(`Unknown source kind: ${String(ref.kind)}`);
  if (!ref.id || typeof ref.id !== 'string') throw new MakeError('Source id is required');
  if (ref.kind !== 'external' && !UUID_RE.test(ref.id)) throw new MakeError(`Source id must be a uuid for ${ref.kind}`);

  switch (ref.kind) {
    case 'article': {
      const { data, error } = await client
        .from('content_posts')
        .select('id, slug, title, excerpt, body')
        .eq('id', ref.id)
        .single();
      if (error || !data) throw new MakeError('Article not found', 404);
      return {
        form: 'article',
        title: data.title ?? null,
        text: [data.excerpt, data.body].filter(Boolean).join('\n\n'),
        platform: 'site',
        sourcePostId: data.id,
        articleUrl: data.slug ? `${SITE}/articles/${data.slug}/` : null,
      };
    }
    case 'piece': {
      const { data, error } = await client
        .from('content_pieces')
        .select('*, source:content_posts!content_pieces_source_post_id_fkey(id, slug)')
        .eq('id', ref.id)
        .single();
      if (error || !data) throw new MakeError('Piece not found', 404);
      const meta = (data.platform_meta ?? null) as Record<string, unknown> | null;
      const form = pieceForm(String(data.piece_type), meta);
      const extras = ['hook', 'caption', 'cta', 'subject']
        .map((k) => (typeof meta?.[k] === 'string' && (meta[k] as string).trim() ? `${k.toUpperCase()}: ${meta[k]}` : ''))
        .filter(Boolean);
      const src = one(data.source as { id: string; slug: string } | { id: string; slug: string }[] | null);
      return {
        form,
        title: data.title ?? null,
        text: [data.body ?? '', ...extras].filter(Boolean).join('\n\n'),
        platform: platformOfForm(form),
        sourcePostId: data.source_post_id ?? null,
        insightId: data.insight_id ?? null,
        angleId: data.angle_id ?? null,
        articleUrl: src?.slug ? `${SITE}/articles/${src.slug}/` : null,
        pieceId: data.id ?? ref.id,
      };
    }
    case 'social_post': {
      const { data, error } = await client
        .from('social_posts')
        .select('*, targets:social_post_targets(platform, format, external_url, metrics)')
        .eq('id', ref.id)
        .single();
      if (error || !data) throw new MakeError('Social post not found', 404);
      const targets = (data.targets ?? []) as Array<{ platform: string; format: string; external_url?: string | null }>;
      const first = targets[0];
      let sourcePostId: string | null = null;
      let insightId: string | null = data.insight_id ?? null;
      let articleUrl: string | null = null;
      let angleId: string | null = null;
      if (data.piece_id) {
        const { data: piece } = await client
          .from('content_pieces')
          .select('source_post_id, insight_id, angle_id, source:content_posts!content_pieces_source_post_id_fkey(slug)')
          .eq('id', data.piece_id)
          .maybeSingle();
        if (piece) {
          sourcePostId = piece.source_post_id ?? null;
          insightId = insightId ?? piece.insight_id ?? null;
          angleId = piece.angle_id ?? null;
          const s = one(piece.source as { slug: string } | { slug: string }[] | null);
          if (s?.slug) articleUrl = `${SITE}/articles/${s.slug}/`;
        }
      }
      return {
        form: socialForm(first?.format, first?.platform),
        title: data.title ?? null,
        text: [data.caption ?? '', data.first_comment ? `FIRST COMMENT: ${data.first_comment}` : ''].filter(Boolean).join('\n\n'),
        platform: first?.platform,
        sourcePostId,
        insightId,
        angleId,
        articleUrl,
      };
    }
    case 'insight': {
      const { data, error } = await client
        .from('content_insights')
        .select('id, line, claim, source_kind, source_ref, source_post_id, evidence_tier, notes')
        .eq('id', ref.id)
        .single();
      if (error || !data) throw new MakeError('Insight not found', 404);
      return {
        // An insight is one line: the shortest form on the scale.
        form: 'ig_lettering',
        title: data.line ?? null,
        text: insightBlock(data),
        platform: 'insight',
        sourcePostId: data.source_post_id ?? null,
        insightId: data.id,
      };
    }
    case 'external': {
      const text = extraContext?.trim();
      if (!text) throw new MakeError('An external source needs its text pasted as extra context (we cannot fetch it).');
      const { form, platform } = externalForm(ref.id);
      return { form, title: ref.id, text, platform, sourcePostId: null, insightId: null };
    }
  }
}

interface InsightRow {
  line: string | null;
  claim?: string | null;
  source_kind?: string | null;
  source_ref?: string | null;
  evidence_tier?: string | null;
  notes?: string | null;
}

function insightBlock(i: InsightRow): string {
  return [
    i.line ? `LINE (Austin's words): ${i.line}` : '',
    i.claim ? `CLAIM: ${i.claim}${i.evidence_tier ? ` (evidence tier: ${i.evidence_tier})` : ''}` : '',
    i.source_ref ? `SOURCE: ${i.source_kind ?? 'other'} · ${i.source_ref}` : '',
    i.notes ? `NOTES: ${i.notes}` : '',
  ]
    .filter(Boolean)
    .join('\n');
}

